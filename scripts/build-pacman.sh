#!/usr/bin/env bash
# build-pacman.sh — Arch Linux package builder for SUB-BROWSER (GPL-3.0)
# If makepkg is available we emit a PKGBUILD directory and use it.
# Otherwise we build the .pkg.tar.zst (or .xz) manually: data tree + .PKGINFO
# (which is exactly what makepkg produces).
set -euo pipefail

VERSION="${VERSION:-2.0.0}"
PKGREL="${PKGREL:-1}"
ARCH="${ARCH:-}"
DIST_DIR="${DIST_DIR:-./dist}"
STAGING="${1:-${STAGING:-}}"

usage() {
  cat <<EOF
Usage: $(basename "$0") [STAGING_DIR]
  STAGING_DIR  compiled tree: bin/sub-browser, share/sub-browser/*, share/icons
Env: VERSION=$VERSION PKGREL=$PKGREL ARCH=$ARCH DIST_DIR=$DIST_DIR
On Arch: uses makepkg with a generated PKGBUILD. Elsewhere: manual .PKGINFO tar.
EOF
}
if [ "${1:-}" = "-h" ] || [ "${1:-}" = "--help" ]; then usage; exit 0; fi

[ -n "$STAGING" ] || { usage >&2; exit 2; }
STAGING="$(readlink -f "$STAGING")"
[ -x "$STAGING/bin/sub-browser" ] || { echo "ERROR: $STAGING/bin/sub-browser missing/not executable" >&2; exit 1; }

if [ -z "$ARCH" ]; then
  case "$(uname -m)" in
    x86_64) ARCH=x86_64 ;; aarch64) ARCH=aarch64 ;;
    *) echo "ERROR: set ARCH (x86_64/aarch64)" >&2; exit 1 ;;
  esac
fi

PKGDIR="$(mktemp -d)"; trap 'rm -rf "$PKGDIR"' EXIT
mkdir -p "$PKGDIR/pkgbuild"

cat > "$PKGDIR/pkgbuild/PKGBUILD" <<'EOF'
# Maintainer: SUB-BROWSER Maintainers <packaging@sub-browser.example>
pkgname=sub-browser
pkgver=__VERSION__
pkgrel=__PKGREL__
pkgdesc="SUB-BROWSER - Gecko/servo-based web browser"
arch=('__ARCH__')
url="https://github.com/subhobhai943/SUB-BROWSER"
license=('GPL3')
# Self-contained Gecko runtime; no webkit2gtk. Edit depends as needed:
depends=()
source=("__STAGING__")
noextract=("__STAGING__")
options=('!strip' 'staticlibs')
package() {
  install -d "$pkgdir/usr/bin" "$pkgdir/usr/share"
  cp -a "$srcdir/bin/." "$pkgdir/usr/bin/" 2>/dev/null || true
  cp -a "$srcdir/share/." "$pkgdir/usr/share/"
}
EOF
sed -e "s|__VERSION__|$VERSION|g" -e "s|__PKGREL__|$PKGREL|g" \
    -e "s|__ARCH__|$ARCH|g" -e "s|__STAGING__|$STAGING|g" \
    -i "$PKGDIR/pkgbuild/PKGBUILD"

mkdir -p "$DIST_DIR"
if command -v makepkg >/dev/null 2>&1 && command -v pacman >/dev/null 2>&1; then
  echo "makepkg detected; building via PKGBUILD (ensure \$STAGING is accessible to makepkg user)"
  ( cd "$PKGDIR/pkgbuild" && makepkg -f --noconfirm --needed --skipchecksums )
  BUILT="$(find "$PKGDIR/pkgbuild" -maxdepth 1 -name 'sub-browser-*.pkg.tar.*' | head -1)"
  cp "$BUILT" "$DIST_DIR/"
  OUT="$DIST_DIR/$(basename "$BUILT")"
else
  echo "makepkg not available; building package manually (.PKGINFO + tar)"
  DATA="$PKGDIR/data"
  mkdir -p "$DATA/usr/bin" "$DATA/usr/share"
  cp -a "$STAGING/bin/." "$DATA/usr/bin/"
  cp -a "$STAGING/share/." "$DATA/usr/share/"
  mkdir -p "$DATA/usr/share/applications"
  cat > "$DATA/usr/share/applications/sub-browser.desktop" <<'DESK'
[Desktop Entry]
Type=Application
Name=SUB-BROWSER
GenericName=Web Browser
Exec=sub-browser %U
Icon=sub-browser
Terminal=false
Categories=Network;WebBrowser;
MimeType=x-scheme-handler/http;x-scheme-handler/https;text/html;
DESK

  SIZE="$(du -sk "$DATA" | cut -f1)"
  BUILT="$(( $(date +%s) ))"
  cat > "$DATA/.PKGINFO" <<EOF
# Generated by build-pacman.sh
pkgname = sub-browser
pkgbase = sub-browser
pkgver = $VERSION-$PKGREL
pkgdesc = SUB-BROWSER - Gecko/servo-based web browser
pkgrel = $PKGREL
url = https://github.com/subhobhai943/SUB-BROWSER
builddate = $BUILT
packager = SUB-BROWSER Maintainers <packaging@sub-browser.example>
size = $SIZE
arch = $ARCH
license = GPL3
EOF

  # zstd preferred by pacman; fall back to xz
  OUT="$DIST_DIR/sub-browser-$VERSION-$PKGREL-$ARCH.pkg.tar.zst"
  if command -v zstd >/dev/null 2>&1; then
    tar --format=gnu --mtime='@0' --owner=0 --group=0 \
      -cf - -C "$DATA" .PKGINFO usr 2>/dev/null | zstd -T0 -19 -o "$OUT" -f
  else
    OUT="$DIST_DIR/sub-browser-$VERSION-$PKGREL-$ARCH.pkg.tar.xz"
    tar --format=gnu --mtime='@0' --owner=0 --group=0 -cJf "$OUT" -C "$DATA" .PKGINFO usr
  fi
fi

echo "== built: $OUT"
echo "-- package contents (first 15) --"
case "$OUT" in
  *.zst) tar -tf "$OUT" 2>/dev/null | head -15 || true ;;
  *.xz)  tar -tJf "$OUT" | head -15 || true ;;
  *)     tar -tf "$OUT" | head -15 || true ;;
esac
echo "-- .PKGINFO --"
case "$OUT" in
  *.zst) tar -xOf "$OUT" .PKGINFO 2>/dev/null || tar -xOf "$OUT" ./PKGINFO ;;
  *) tar -xJf "$OUT" .PKGINFO 2>/dev/null || tar -xJf "$OUT" ./PKGINFO ;;
esac | head -20 || true
sha256sum "$OUT"
